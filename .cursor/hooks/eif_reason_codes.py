def is_reason_code(code):
    return isinstance(code, str) and code in REASON_CODES


def require_reason_code(code):
    if not is_reason_code(code):
        raise ValueError(f'UNKNOWN_REASON_CODE: {code!r} is not in the EIF reason registry')
    return code
