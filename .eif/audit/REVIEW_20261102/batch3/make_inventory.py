"""Builds CHART_CALLERS.md: every caller of the shared charts (apps/web/src, product code), and which shared parts it uses.

Reads the JSX with the same brace-depth scan as web/chart_callers_probe.py. The classification rules are the ones the test
`workbench-ui/chartCallers.test.ts` enforces; the time/category judgement per TrendChart caller was made by reading each caller.
Run from the repo root:  python .eif/audit/REVIEW_20261102/batch3/make_inventory.py
"""
import pathlib
import re

ROOT = pathlib.Path("apps/web/src")
NAMES = ["CategoryBars", "PairedBars", "TrendChart", "RankedBars", "ShareChart", "ScatterPlot"]
pat = re.compile(r"<(" + "|".join(NAMES) + r")\b")
TIME_X = {  # TrendChart callers whose x is time (period, week, date): they need no category tick, sort or top N
    "app/(app)/sell-out/ChannelOpsOverviewTab.tsx": "week", "features/dashboards/WidgetChart.tsx": "period",
    "features/market-listings/MarketSurface.tsx": "date", "features/plan-vs-executed/PlanVsExecutedView.tsx": "period",
    "features/reports/ReportBuilderView.tsx": "period", "features/stock/CoverLensView.tsx": "week",
    "features/stock/MovementLensView.tsx": "week", "features/stock/SellThroughOverview.tsx": "period",
    "features/dashboards/builder/V2WidgetBody.tsx": "period",
}
ORDERED_OFF = {"features/promotions-funding/CaseBookSurface.tsx": "age buckets", "features/stock/CoverLensView.tsx": "cover buckets",
               "features/supply-inbound/SupplyOverview.tsx": "lifecycle states"}
rows = []
for f in sorted(ROOT.rglob("*.tsx")):
    rel = f.relative_to(ROOT).as_posix()
    if f.name.endswith(".test.tsx") or rel.startswith("design-lab/") or rel == "features/workbench-ui/charts.tsx":
        continue
    s = f.read_text(encoding="utf-8")
    if "workbench-ui/charts" not in s:
        continue
    for m in pat.finditer(s):
        i, depth = m.end(), 0
        while i < len(s):
            ch = s[i]
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
            elif ch == ">" and depth == 0 and s[i - 1] != "=":
                break
            i += 1
        tag = s[m.start():i + 1]
        props = set(re.findall(r"\b([A-Za-z][A-Za-z0-9]*)\s*=\s*[{\"']", tag))
        name = m.group(1)
        line = s.count("\n", 0, m.start()) + 1
        titles = "yes" if {"xAxisTitle", "yAxisTitle"} <= props else ("n/a (no axes)" if name == "ShareChart" else "NO")
        unit = "yes" if props & {"unit", "xUnit"} else "NO"
        if name == "ShareChart":
            tick, ctl, legend = "n/a (names listed)", "top N / sort (shared, default on)", "yes (always)"
        elif name == "ScatterPlot":
            tick, ctl, legend = "n/a (points)", "n/a", "n/a"
        elif name == "TrendChart":
            if "categoryAxis" in props:
                tick, ctl, legend = "yes (shared tick)", "yes (categoryAxis: Sort + top N)", "yes (default when more than one series)"
            else:
                tick, ctl, legend = f"n/a (time axis: {TIME_X.get(rel, 'period')})", "n/a (time axis)", "yes (default when more than one series)" if "legend" not in props else "off (one series)"
        else:
            tick = "yes (shared tick)"
            if re.search(r"controls=\{false\}", tag):
                ctl = f"off, ordered {ORDERED_OFF.get(rel, '?')} (commented in code)"
            elif "controls" in props:
                ctl = "yes (container-owned state)"
            else:
                ctl = "yes (Sort + top N, default on)"
            legend = "yes (two series)" if name == "PairedBars" else "n/a (one series)"
        rows.append((f"{rel}:{line}", name, titles, unit, legend, tick, ctl))

out = ["# Chart caller inventory (GOV-008 batch 3)", "",
       f"{len(rows)} callers of the shared charts in product code (`apps/web/src`, not `design-lab/`). Generated by `make_inventory.py`; enforced by `apps/web/src/features/workbench-ui/chartCallers.test.ts`.", "",
       "| Caller | Chart | Axis titles | Unit | Legend | Long-name tick | Sort / top N |", "|---|---|---|---|---|---|---|"]
out += ["| " + " | ".join(r) + " |" for r in rows]
bad = [r for r in rows if "NO" in r]
out += ["", f"Callers missing a title or a unit: **{len(bad)}**.", "",
        "Not in scope: the 13 design-lab surfaces under `src/design-lab/surfaces/` use the design lab's own chart primitives (`design-lab/primitives/charts`), "
        "not the shared components, with fixture data on `/design-lab/*` routes; they were not changed.", "",
        "Fixed in this batch: the dual-axis widget (`V2WidgetBody`) had no category tick, no Sort and no top N, and no unit prop; the comparison chart listed "
        "every series after the top N; the table widget ignored the saved sort. All three now use the shared parts."]
pathlib.Path(".eif/audit/REVIEW_20261102/batch3/CHART_CALLERS.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(rows), "callers;", len(bad), "missing")
